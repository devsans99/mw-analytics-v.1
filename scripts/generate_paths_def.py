"""Generate documentations/paths_def.md: every .py file with its classes and functions.

Includes a route table (Flask route decorators) and CLI commands.
Usage (from the project root):  python scripts/generate_paths_def.py
Standard library only (uses `ast`). Exclusions are configured in scripts/_common.py.
"""
from __future__ import annotations

import ast
from dataclasses import dataclass
from pathlib import Path

from _common import ROOT, iter_files, write_doc

# URL prefix of blueprints, by directory. Shown in the route table.
BLUEPRINT_PREFIXES = {"app/cms/": "/<ADMIN_URL_PREFIX>"}
HTTP_SHORTCUTS = {"get", "post", "put", "patch", "delete"}


@dataclass
class Route:
    methods: str
    path: str
    func: str
    file: str
    line: int


def decorator_info(decorator: ast.expr, rel: str):
    """Return ('route', methods, path) / ('cli', name) / ('other', text) for a decorator."""
    if isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Attribute):
        attr = decorator.func.attr
        first = decorator.args[0] if decorator.args else None
        literal = first.value if isinstance(first, ast.Constant) and isinstance(first.value, str) else None
        if attr == "route" and literal is not None:
            methods = "GET"
            for keyword in decorator.keywords:
                if keyword.arg == "methods":
                    try:
                        methods = ",".join(ast.literal_eval(keyword.value))
                    except ValueError:
                        methods = "?"
            return "route", methods, literal
        if attr in HTTP_SHORTCUTS and literal is not None:
            return "route", attr.upper(), literal
        if attr == "command" and ast.unparse(decorator.func).endswith("cli.command"):
            return "cli", literal or "", ""
    return "other", ast.unparse(decorator), ""


def describe_function(node, rel: str, routes: list[Route], indent: int) -> list[str]:
    args = ast.unparse(node.args)
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    keyword = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
    tags = []
    for decorator in node.decorator_list:
        kind, a, b = decorator_info(decorator, rel)
        if kind == "route":
            tags.append(f"`{a} {b}`")
            prefix = next((p for d, p in BLUEPRINT_PREFIXES.items() if rel.startswith(d)), "")
            routes.append(Route(a, prefix + b, node.name, rel, node.lineno))
        elif kind == "cli":
            tags.append(f"`flask {a or node.name.replace('_', '-')}`")
        else:
            tags.append(f"`@{a}`")
    doc = ast.get_docstring(node)
    summary = f" — {doc.splitlines()[0]}" if doc else ""
    tag_text = f" [{' '.join(tags)}]" if tags else ""
    pad = "  " * indent
    return [f"{pad}- `{keyword} {node.name}({args}){returns}` L{node.lineno}{tag_text}{summary}"]


def walk(body, rel: str, routes: list[Route], indent: int = 0) -> list[str]:
    lines: list[str] = []
    for node in body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            lines += describe_function(node, rel, routes, indent)
            lines += walk(node.body, rel, routes, indent + 1)  # nested defs (e.g. CLI commands)
        elif isinstance(node, ast.ClassDef):
            bases = ", ".join(ast.unparse(base) for base in node.bases)
            doc = ast.get_docstring(node)
            summary = f" — {doc.splitlines()[0]}" if doc else ""
            lines.append(f"{'  ' * indent}- `class {node.name}({bases})` L{node.lineno}{summary}")
            lines += walk(node.body, rel, routes, indent + 1)
    return lines


def main() -> None:
    routes: list[Route] = []
    sections: list[str] = []
    for path in iter_files(".py"):
        rel = path.as_posix()
        try:
            tree = ast.parse((ROOT / path).read_text(encoding="utf-8"), filename=rel)
        except SyntaxError as exc:
            sections.append(f"## {rel}\n\n- SYNTAX ERROR: {exc}\n")
            continue
        module_doc = ast.get_docstring(tree)
        lines = walk(tree.body, rel, routes)
        header = f"## {rel}\n"
        if module_doc:
            header += f"\n_{module_doc.splitlines()[0]}_\n"
        sections.append(header + "\n" + ("\n".join(lines) if lines else "- (no classes or functions)") + "\n")

    route_rows = ["| Methods | URL | Function | Location |", "|---|---|---|---|"]
    for route in sorted(routes, key=lambda r: (r.path, r.methods)):
        route_rows.append(
            f"| {route.methods} | `{route.path}` | `{route.func}` | {route.file}:{route.line} |"
        )

    text = (
        "# Python paths and definitions\n\n"
        "Generated by `scripts/generate_paths_def.py`. Do not edit by hand.\n\n"
        "CMS URLs start with the secret `/<ADMIN_URL_PREFIX>` (set in `.env`).\n\n"
        "## Route table\n\n" + "\n".join(route_rows) + "\n\n"
        "# Definitions by file\n\n" + "\n".join(sections)
    )
    write_doc("paths_def.md", text)


if __name__ == "__main__":
    main()

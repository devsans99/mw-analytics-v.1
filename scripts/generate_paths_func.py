"""Generate documentations/paths_func.md: functions found in every .js/.mjs file.

Detects function declarations, arrow functions assigned to variables, method shorthand
(e.g. Alpine component methods) and Alpine.data("name", ...) registrations.
Usage (from the project root):  python scripts/generate_paths_func.py
Standard library only (regex based). Exclusions are configured in scripts/_common.py.
"""
from __future__ import annotations

import re

from _common import ROOT, iter_files, write_doc

FUNCTION_DECL = re.compile(r"^\s*(?:export\s+)?(?:default\s+)?(async\s+)?function\s*\*?\s*(\w+)\s*\(([^)]*)\)")
ARROW = re.compile(
    r"^\s*(?:export\s+)?(?:const|let|var)\s+(\w+)\s*=\s*(async\s+)?(?:\(([^)]*)\)|(\w+))\s*=>"
)
ALPINE_DATA = re.compile(r"""Alpine\.data\(\s*['"]([\w-]+)['"]""")
METHOD = re.compile(r"^\s{2,}(async\s+)?(?:get\s+|set\s+)?(\w+)\s*\(([^)]*)\)\s*\{")
KEYWORDS = {"if", "for", "while", "switch", "catch", "function", "return", "else", "try"}


def scan(text: str) -> list[str]:
    results = []
    for number, line in enumerate(text.splitlines(), start=1):
        stripped = line.strip()
        if stripped.startswith(("//", "*", "/*")):
            continue
        if match := ALPINE_DATA.search(line):
            results.append(f"- L{number} `Alpine.data(\"{match.group(1)}\")` — Alpine component")
        elif match := FUNCTION_DECL.match(line):
            prefix = "async " if match.group(1) else ""
            results.append(f"- L{number} `{prefix}function {match.group(2)}({match.group(3).strip()})`")
        elif match := ARROW.match(line):
            params = (match.group(3) if match.group(3) is not None else match.group(4)) or ""
            prefix = "async " if match.group(2) else ""
            results.append(f"- L{number} `{prefix}{match.group(1)}({params.strip()}) =>`")
        elif (match := METHOD.match(line)) and match.group(2) not in KEYWORDS:
            prefix = "async " if match.group(1) else ""
            results.append(f"- L{number} `{prefix}{match.group(2)}({match.group(3).strip()})` — method")
    return results


def main() -> None:
    sections = []
    total = 0
    for path in iter_files(".js", ".mjs"):
        found = scan((ROOT / path).read_text(encoding="utf-8"))
        total += len(found)
        body = "\n".join(found) if found else "- (no functions found)"
        sections.append(f"## {path.as_posix()}\n\n{body}\n")

    text = (
        "# JavaScript functions\n\n"
        "Generated by `scripts/generate_paths_func.py`. Do not edit by hand.\n\n"
        f"{total} functions in {len(sections)} files "
        "(vendor libraries and minified files excluded; inline Alpine expressions in templates are not scanned).\n\n"
        + "\n".join(sections)
    )
    write_doc("paths_func.md", text)


if __name__ == "__main__":
    main()

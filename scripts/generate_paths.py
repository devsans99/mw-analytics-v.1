"""Generate documentations/paths.md: the project file tree.

Usage (from the project root):  python scripts/generate_paths.py
Standard library only. Exclusions are configured in scripts/_common.py.
"""
from __future__ import annotations

from _common import iter_files, write_doc


def build_tree(paths) -> dict:
    tree: dict = {}
    for path in paths:
        node = tree
        for part in path.parts[:-1]:
            node = node.setdefault(part, {})
        node[path.parts[-1]] = None  # None marks a file
    return tree


def render(tree: dict, prefix: str = "") -> list[str]:
    lines = []
    # Directories first, then files, each alphabetically.
    entries = sorted(tree.items(), key=lambda item: (item[1] is None, item[0].lower()))
    for index, (name, child) in enumerate(entries):
        last = index == len(entries) - 1
        lines.append(f"{prefix}{'└── ' if last else '├── '}{name}{'/' if child is not None else ''}")
        if child is not None:
            lines.extend(render(child, prefix + ("    " if last else "│   ")))
    return lines


def main() -> None:
    files = list(iter_files())
    lines = ["mwa/", *render(build_tree(files))]
    text = (
        "# Project paths\n\n"
        "Generated by `scripts/generate_paths.py`. Do not edit by hand.\n\n"
        f"{len(files)} files (build output, vendor libraries, uploads, lock files and secrets excluded).\n\n"
        "```text\n" + "\n".join(lines) + "\n```\n"
    )
    write_doc("paths.md", text)


if __name__ == "__main__":
    main()
